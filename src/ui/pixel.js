export function pixelWord(text, { cell = 10, gap = 1, color = '#e9edff', shadow = null, spacing = 1 } = {}) {
  const chars = [...String(text).toUpperCase()].map((c) => G[c] ?? G['?']);
  const w = chars.length * (5 + spacing) - spacing;
  const canvas = document.createElement('canvas');
  canvas.className = 'pixel-word';
  canvas.width = w * cell;
  canvas.height = 7 * cell;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  if (shadow) { ctx.shadowColor = shadow; ctx.shadowBlur = cell * 1.2; }
  ctx.fillStyle = color;
  chars.forEach((bits, i) => {
    for (let k = 0; k < 35; k++) {
      if (bits[k] !== '1') continue;
      const x = (i * (5 + spacing) + (k % 5)) * cell;
      const y = Math.floor(k / 5) * cell;
      ctx.fillRect(x + gap, y + gap, cell - gap * 2, cell - gap * 2);
    }
  });
  return canvas;
}

export const hasGlyph = (c) => c.toUpperCase() in G;
